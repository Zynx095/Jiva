import { useEffect, useMemo, useState } from 'react';
import { CardHeader, JivaButton, JivaCard, cx, describeEvent, formatClockSeconds, type JivaEvent } from '@jiva/ui/src';
import { call } from './api';
import { DEMO, PRACTITIONER_PERSONA } from './workflows';
import type { LiveState } from './useLiveState';

interface AuditEntry {
  auditId: string;
  at: string;
  actor: { role: string; userId?: string; hospitalId?: string };
  action: string;
  outcome: 'ALLOWED' | 'DENIED';
  entityType: string;
  entityId?: string;
  reasonCode?: string;
}

type Row =
  | { kind: 'event'; id: string; at: string; e: JivaEvent }
  | { kind: 'audit'; id: string; at: string; a: AuditEntry };

const NAMES: Record<string, string> = { 'HOSP-BLR-001': 'Hebbal', 'HOSP-BLR-002': 'Whitefield', 'HOSP-BLR-003': 'Koramangala', 'HOSP-BLR-004': 'Indiranagar' };

/** Where an event's facts come from. In demo mode every actor is a demo persona and every input synthetic. */
function provenance(e: JivaEvent): { label: string; cls: string } {
  const p = e.payload ?? {};
  const trusted = (e.metadata?.trustedEvidence as { status?: string } | undefined)?.status;
  if (p.dataStatus === 'SYNTHETIC_DEMO' || trusted === 'SYNTHETIC_DEMO') return { label: 'Synthetic · demo persona', cls: 'bg-amber-50 text-amber-900 ring-amber-200' };
  if (e.source?.type === 'system') return { label: 'Derived by JIVA from synthetic inputs', cls: 'bg-ink-50 text-ink-700 ring-ink-200' };
  return { label: 'Synthetic · demo persona', cls: 'bg-amber-50 text-amber-900 ring-amber-200' };
}

/**
 * What was actually recorded, as the server returns it: the event ledger (read as the demo administrator,
 * which excludes clinical content by design), the clinical events the assigned doctor may see, and the
 * content-free audit trail. Nothing here is generated by the portal.
 */
export function TimelineView({ live }: { live: LiveState }) {
  const [events, setEvents] = useState<JivaEvent[] | null>(null);
  const [audit, setAudit] = useState<AuditEntry[] | null>(null);
  const [caseOnly, setCaseOnly] = useState(true);
  const [showAudit, setShowAudit] = useState(true);
  const [showGps, setShowGps] = useState(false);
  const doctorPersona = live.encounter?.assignedDoctor?.practitionerId ? PRACTITIONER_PERSONA[live.encounter.assignedDoctor.practitionerId] : undefined;

  const [manual, setManual] = useState(0);
  useEffect(() => {
    let alive = true;
    const load = async () => {
      const [hist, clinical] = await Promise.all([
        call<JivaEvent[]>(DEMO.admin, 'GET', '/api/events/history?limit=1000').catch(() => null),
        doctorPersona ? call<JivaEvent[]>(doctorPersona, 'GET', `/api/cases/${DEMO.caseId}/timeline`).catch(() => null) : Promise.resolve(null),
      ]);
      if (!alive) return;
      const merged = new Map<string, JivaEvent>();
      for (const e of [...(hist?.ok && Array.isArray(hist.body) ? hist.body : []), ...(clinical?.ok && Array.isArray(clinical.body) ? clinical.body : [])]) merged.set(e.eventId, e);
      setEvents(hist ? [...merged.values()] : null);
    };
    void load();
    return () => {
      alive = false;
    };
  }, [live.version, doctorPersona, manual]);

  // Reading the audit log is itself audited, so it is read when the recorded events change (or on request),
  // not on every poll; the portal's own audit reads are not listed.
  const signature = `${events?.length ?? 0}|${caseOnly}|${manual}`;
  useEffect(() => {
    let alive = true;
    void call<{ entries: AuditEntry[] }>(DEMO.admin, 'GET', `/api/audit?limit=1000${caseOnly ? `&caseId=${DEMO.caseId}` : ''}`)
      .then((au) => alive && setAudit(au.ok ? au.body.entries.filter((x) => x.action !== 'audit.read') : null))
      .catch(() => alive && setAudit(null));
    return () => {
      alive = false;
    };
  }, [signature, caseOnly]);

  const rows = useMemo(() => {
    const out: Row[] = [];
    for (const e of events ?? []) {
      const caseId = e.patientId ?? (typeof e.payload?.caseId === 'string' ? e.payload.caseId : undefined);
      if (caseOnly && caseId !== DEMO.caseId && e.eventType !== 'demo.reset') continue;
      if (!showGps && e.eventType === 'ambulance.location.updated') continue;
      out.push({ kind: 'event', id: e.eventId, at: e.timestamp, e });
    }
    if (showAudit) for (const a of audit ?? []) out.push({ kind: 'audit', id: a.auditId, at: a.at, a });
    return out.sort((x, y) => Date.parse(y.at) - Date.parse(x.at)).slice(0, 400);
  }, [events, audit, caseOnly, showAudit, showGps]);

  return (
    <JivaCard>
      <CardHeader
        title="Recorded timeline"
        icon="clock"
        subtitle="Events and audit entries exactly as the server recorded them · clinical events carry identifiers only, never content"
        actions={
          <JivaButton size="sm" variant="ghost" icon="refresh" onClick={() => setManual((m) => m + 1)}>
            Refresh
          </JivaButton>
        }
      />
      <div className="mt-3 flex flex-wrap gap-3 text-[13px] text-ink-800">
        <label className="inline-flex items-center gap-1.5">
          <input type="checkbox" className="h-4 w-4 accent-amber-700" checked={caseOnly} onChange={(e) => setCaseOnly(e.target.checked)} />
          Only {DEMO.caseId}
        </label>
        <label className="inline-flex items-center gap-1.5">
          <input type="checkbox" className="h-4 w-4 accent-amber-700" checked={showAudit} onChange={(e) => setShowAudit(e.target.checked)} />
          Audit entries (incl. refused attempts)
        </label>
        <label className="inline-flex items-center gap-1.5">
          <input type="checkbox" className="h-4 w-4 accent-amber-700" checked={showGps} onChange={(e) => setShowGps(e.target.checked)} />
          GPS updates
        </label>
      </div>
      <p className="mt-2 text-xs text-ink-600">
        Labels: <span className="rounded-full bg-amber-50 px-1.5 font-semibold text-amber-900 ring-1 ring-inset ring-amber-200">Synthetic · demo persona</span> recorded from a demo persona's action;{' '}
        <span className="rounded-full bg-ink-50 px-1.5 font-semibold text-ink-700 ring-1 ring-inset ring-ink-200">Derived by JIVA</span> produced by JIVA's engines from those synthetic inputs. Everything in a demo-mode API is synthetic.
      </p>
      {events === null ? (
        <p className="mt-3 text-sm text-danger-700">The event ledger could not be read.</p>
      ) : rows.length === 0 ? (
        <p className="mt-3 text-sm text-ink-500">Nothing recorded yet for this view.</p>
      ) : (
        <ol className="mt-3 divide-y divide-ink-100">
          {rows.map((r) => (r.kind === 'event' ? <EventRow key={r.id} e={r.e} /> : <AuditRow key={r.id} a={r.a} />))}
        </ol>
      )}
    </JivaCard>
  );
}

function EventRow({ e }: { e: JivaEvent }) {
  const d = describeEvent(e, (id) => NAMES[id], 'ops');
  const prov = provenance(e);
  return (
    <li className="flex flex-wrap items-start gap-x-3 gap-y-1 py-2">
      <span className="w-20 shrink-0 font-mono text-xs tabular-nums text-ink-500">{formatClockSeconds(e.timestamp)}</span>
      <div className="min-w-0 flex-1">
        <p className="text-[13px] font-semibold text-ink-900">{d.title}</p>
        {d.detail && <p className="text-xs text-ink-600">{d.detail}</p>}
        <p className="font-mono text-[11px] text-ink-500">
          {e.eventType} · {e.source?.type}:{e.source?.id}
        </p>
      </div>
      <span className={cx('shrink-0 rounded-full px-2 py-0.5 text-[11px] font-semibold ring-1 ring-inset', prov.cls)}>{prov.label}</span>
    </li>
  );
}

function AuditRow({ a }: { a: AuditEntry }) {
  return (
    <li className="flex flex-wrap items-start gap-x-3 gap-y-1 bg-ink-25/60 py-2">
      <span className="w-20 shrink-0 font-mono text-xs tabular-nums text-ink-500">{formatClockSeconds(a.at)}</span>
      <div className="min-w-0 flex-1">
        <p className="text-[13px] text-ink-800">
          <span className="font-semibold">Audit:</span> {a.action} by {a.actor.role.toLowerCase()}
          {a.entityId ? ` · ${a.entityType.toLowerCase()} ${a.entityId}` : ` · ${a.entityType.toLowerCase()}`}
          {a.reasonCode ? ` · reason ${a.reasonCode}` : ''}
        </p>
      </div>
      <span className={cx('shrink-0 rounded-full px-2 py-0.5 text-[11px] font-semibold ring-1 ring-inset', a.outcome === 'ALLOWED' ? 'bg-brand-50 text-brand-800 ring-brand-200' : 'bg-danger-50 text-danger-700 ring-danger-200')}>
        {a.outcome === 'ALLOWED' ? 'Allowed' : 'Refused'}
      </span>
    </li>
  );
}
